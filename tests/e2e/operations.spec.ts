import { expect, test, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';

async function signIn(page: Page) {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore demo workspace' }).click();
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible();
}
async function go(page: Page, name: string) {
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click();
}
const unique = (prefix: string) => `${prefix} ${Date.now()}`;

test('volunteer onboarding edits persist with availability and administrative readiness', async ({ page }) => {
  await signIn(page);
  await go(page, 'Volunteers');
  const name = unique('Review Volunteer');
  await page.getByRole('button', { name: 'Add volunteer', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Close dialog', exact: true })).toBeFocused();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially(name, { delay: 30 });
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveValue(name);
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('coordinator-review@example.invalid');
  await page.getByRole('combobox', { name: 'Programme status' }).selectOption('active');
  await page.getByRole('textbox', { name: 'Skills', exact: true }).fill('Wayfinding, Library support');
  await page.getByRole('textbox', { name: 'Languages', exact: true }).fill('Japanese, English');
  await page.getByRole('combobox', { name: 'Training status', exact: true }).selectOption('complete');
  await page.getByRole('combobox', { name: 'Health administration status' }).selectOption('cleared');
  const reviewDate = new Date(`${await page.getByLabel('Workspace date', { exact: true }).inputValue()}T12:00:00Z`);
  reviewDate.setUTCFullYear(reviewDate.getUTCFullYear() + 1);
  await page.getByLabel('Next clearance review', { exact: true }).fill(reviewDate.toISOString().slice(0, 10));
  await page.getByLabel('Maximum hours per week', { exact: true }).fill('10');
  await page.getByRole('checkbox', { name: 'Fri', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Save volunteer', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await page.getByRole('textbox', { name: 'Search volunteers' }).fill(name);
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: `View ${name}`, exact: true }).click();
  await expect(page.getByText('10h maximum per week', { exact: false })).toBeVisible();
  await page.getByRole('tab', { name: 'Eligibility', exact: true }).click();
  await expect(page.getByText('Ready for compatible shifts', { exact: true })).toBeVisible();
  const state = await (await page.request.get('/api/state')).json();
  const saved = state.volunteers.find((v: any) => v.name === name);
  expect(saved.availability).toEqual(['mon', 'tue', 'wed', 'thu']);
  expect(saved.skills).toEqual(['Wayfinding', 'Library support']);
  expect(saved.healthStatus).toBe('cleared');
  expect(saved.maxHoursPerWeek).toBe(10);
});

test('record correction survives reload and updates the monthly report and CSV', async ({ page }) => {
  await signIn(page);
  await go(page, 'Activity records');
  await page.getByRole('button', { name: 'All dates', exact: true }).click();
  const notes = unique('Verified participation correction');
  await page.locator('tbody tr').first().getByRole('button', { name: /Edit record for/ }).click();
  await page.getByLabel('Actual hours', { exact: true }).fill('1.25');
  await page.getByLabel('Service interactions', { exact: true }).fill('37');
  await page.getByRole('textbox', { name: 'Activity notes' }).fill(notes);
  const response = page.waitForResponse(r => r.url().includes('/api/records/') && r.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save activity', exact: true }).click();
  const saved = await (await response).json();
  expect(saved.hours).toBe(1.25);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: 'All dates', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search activity records' }).fill(notes);
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('tbody tr').getByText('1.3 h', { exact: true })).toBeVisible();
  const state = await (await page.request.get('/api/state')).json();
  expect(state.records.find((r: any) => r.id === saved.id).serviceCount).toBe(37);
  const month = saved.date.slice(0, 7);
  const total = state.records.filter((r: any) => r.date.startsWith(month)).reduce((sum: number, r: any) => sum + r.hours, 0);
  await go(page, 'Reports & insights');
  await page.getByLabel('Reporting period', { exact: true }).fill(month);
  await expect(page.locator('.op-stat').filter({ has: page.getByText('Volunteer hours', { exact: true }) }).locator('strong')).toHaveText(total.toFixed(1));
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  const download = await downloadEvent;
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv).toContain('Recorded hours');
  expect(csv).toContain(month);
  expect(download.suggestedFilename()).toBe(`volunteer-monthly-report-${month}.csv`);
});

