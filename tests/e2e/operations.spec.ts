test('resource availability validates quantity, maintenance removes capacity, and deletion persists', async ({ page }) => {
  await signIn(page);
  await go(page, 'Resources');
  const name = unique('Review mobility supplies');
  await page.getByRole('button', { name: 'Add resource', exact: true }).click();
  await page.getByRole('textbox', { name: 'Resource name', exact: true }).fill(name);
  await page.getByLabel('Total quantity', { exact: true }).fill('4');
  await page.getByLabel('Available quantity', { exact: true }).fill('5');
  await page.getByRole('button', { name: 'Save resource', exact: true }).click();
  expect(await page.getByLabel('Available quantity', { exact: true }).evaluate((el: HTMLInputElement) => el.validity.rangeOverflow)).toBe(true);
  await page.getByLabel('Available quantity', { exact: true }).fill('3');
  await page.getByRole('button', { name: 'Save resource', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await page.getByRole('textbox', { name: 'Search resources' }).fill(name);
  await page.getByRole('button', { name, exact: true }).click();
  await expect(page.getByText('3 / 4', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Update resource', exact: true }).click();
  await page.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('maintenance');
  await expect(page.getByLabel('Available quantity', { exact: true })).toHaveValue('0');
  await page.getByRole('button', { name: 'Save resource', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const state = await (await page.request.get('/api/state')).json();
  expect(state.resources.find((r: any) => r.name === name).available).toBe(0);
  await page.getByRole('button', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('button', { name: 'Remove resource', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await page.getByRole('textbox', { name: 'Search resources' }).fill(name);
  await expect(page.getByRole('heading', { name: 'No resources match' })).toBeVisible();
  const after = await (await page.request.get('/api/state')).json();
  expect(after.resources.some((r: any) => r.name === name)).toBe(false);
  expect(after.audit.some((a: any) => a.action === 'delete' && a.summary.includes(name))).toBe(true);
});

test('administrator creates and changes account roles and downloads a credential-free backup', async ({ page }) => {
  await signIn(page);
  await go(page, 'Workspace settings');
  await page.getByRole('tab', { name: 'Access & accounts', exact: true }).click();
  const name = unique('Operations reviewer');
  const username = `reviewer-${Date.now()}`;
  await page.getByRole('button', { name: 'Add account', exact: true }).click();
  await page.getByRole('textbox', { name: 'Account holder name', exact: true }).fill(name);
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill(username);
  await page.getByLabel('Initial password', { exact: true }).fill('Testing-Workspace-42!');
  await page.getByRole('button', { name: 'Save account', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const row = page.locator('tbody tr').filter({ hasText: username });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'Edit', exact: false }).click();
  await page.getByRole('combobox', { name: 'Access role', exact: true }).selectOption('viewer');
  await page.getByRole('button', { name: 'Save account', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(row.getByText('viewer', { exact: true })).toBeVisible();
  const users = await (await page.request.get('/api/users')).json();
  expect(users.find((u: any) => u.username === username).role).toBe('viewer');
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download backup', exact: true }).click();
  const download = await downloadEvent;
  const backupText = await readFile((await download.path())!, 'utf8');
  const backup = JSON.parse(backupText);
  expect(backup.format).toBe('shuori-backup');
  expect(backup.schemaVersion).toBe(1);
  expect(backup.users.some((u: any) => u.username === username)).toBe(true);
  expect(backup.state.audit.length).toBeGreaterThan(0);
  expect(backupText).not.toContain('password_hash');
  expect(backupText).not.toContain('Testing-Workspace-42!');
  expect(backup).not.toHaveProperty('sessions');
});

test('viewer can inspect operations but cannot mutate or access backup and account administration', async ({ page }) => {
  const login = await page.request.post('/api/demo-login', { data: { username: 'viewer' } });
  expect(login.ok()).toBe(true);
  const session = await login.json();
  await page.goto('/');
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible();
  await go(page, 'Volunteers');
  await expect(page.getByRole('button', { name: 'Add volunteer', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: /^View / }).first().click();
  await expect(page.getByRole('button', { name: 'Edit profile', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await go(page, 'Activity records');
  await expect(page.getByRole('button', { name: 'Log activity', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: /Edit record for/ })).toHaveCount(0);
  await go(page, 'Support & improvement');
  await expect(page.getByRole('button', { name: 'New request', exact: true })).toHaveCount(0);
  await go(page, 'Resources');
  await expect(page.getByRole('button', { name: 'Add resource', exact: true })).toHaveCount(0);
  await go(page, 'Workspace settings');
  await expect(page.getByRole('tab', { name: 'Access & accounts', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Download backup', exact: true })).toHaveCount(0);
  const mutation = await page.request.post('/api/volunteers', { headers: { 'X-CSRF-Token': session.csrfToken }, data: { name: 'Denied viewer write' } });
  expect(mutation.status()).toBe(403);
  expect((await page.request.get('/api/backup')).status()).toBe(403);
  expect((await page.request.get('/api/users')).status()).toBe(403);
});
